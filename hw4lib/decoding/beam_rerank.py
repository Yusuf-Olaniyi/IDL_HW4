"""Deterministic beam search with a compact KV cache, plus entity-coverage reranking.

Every returned string is text generated by the model. The decoder only

* keeps the ``beam_width`` most probable continuations (beam search),
* blocks EOS for the first ``min_new_tokens`` tokens (no empty outputs),
* forbids repeating any ``no_repeat_ngram_size``-token sequence (no loops),

and the reranker chooses, among those model-generated candidates, the one that
mentions the most entity names given in the input triples (ties broken by the
length-normalised model log-probability).
"""
from __future__ import annotations

import re

import torch


def _banned_tokens(generated: list[int], n: int) -> set[int]:
    """Tokens that would complete an n-gram already present in ``generated``."""
    if n <= 0 or len(generated) < n - 1:
        return set()
    prefix = tuple(generated[len(generated) - (n - 1):]) if n > 1 else ()
    banned = set()
    for i in range(len(generated) - n + 1):
        if tuple(generated[i:i + n - 1]) == prefix:
            banned.add(generated[i + n - 1])
    return banned


def _expand_cache(cache, width: int):
    return tuple((k.repeat(width, 1, 1, 1), v.repeat(width, 1, 1, 1)) for k, v in cache)


def _select_cache(cache, index: torch.Tensor):
    return tuple((k.index_select(0, index), v.index_select(0, index)) for k, v in cache)


@torch.inference_mode()
def beam_search(model, prompt_ids: list[int], eos_id: int, *, beam_width: int = 4,
                max_new_tokens: int = 128, max_len: int | None = None,
                no_repeat_ngram_size: int = 0, min_new_tokens: int = 0,
                length_penalty: float = 1.0, device: str | torch.device = "cpu"):
    """Return candidates ``[(generated_ids, normalised_logprob), ...]`` best first.

    ``generated_ids`` excludes the prompt and the final EOS.
    Uses ``model.score_cached`` (RoPE models) when available, else ``model.score``.
    """
    if beam_width < 1:
        raise ValueError("beam_width must be >= 1")
    max_len = max_len or model.max_len
    budget = min(max_new_tokens, max_len - len(prompt_ids))
    if budget <= 0:
        raise ValueError("Prompt does not leave room for generation")
    use_cache = hasattr(model, "score_cached") and getattr(model, "use_rope", False)
    prompt = torch.tensor([prompt_ids], dtype=torch.long, device=device)

    if use_cache:
        logits, cache = model.score_cached(prompt, None)             # (1, V)
    else:
        logits, cache = model.score(prompt), None
    log_probs = torch.log_softmax(logits.float(), dim=-1)[0]          # (V,)

    beams = [([], 0.0)]                                               # (tokens, sum logprob)
    finished = []                                                     # (tokens, sum logprob)
    step_log_probs = log_probs.unsqueeze(0)                           # (1, V)

    for step in range(budget):
        candidates = []
        for b, (tokens, score) in enumerate(beams):
            lp = step_log_probs[b].clone()
            if step < min_new_tokens:
                lp[eos_id] = -float("inf")
            for t in _banned_tokens(tokens, no_repeat_ngram_size):
                lp[t] = -float("inf")
            top_lp, top_ids = torch.topk(lp, beam_width + 1)
            for value, token in zip(top_lp.tolist(), top_ids.tolist()):
                if value == -float("inf"):
                    continue
                candidates.append((score + value, b, token))
        candidates.sort(key=lambda item: -item[0])

        new_beams, parents = [], []
        for total, b, token in candidates:
            tokens = beams[b][0]
            if token == eos_id:
                finished.append((tokens, total))
            else:
                new_beams.append((tokens + [token], total))
                parents.append(b)
            if len(new_beams) == beam_width:
                break
        # Stop once enough finished hypotheses beat every live beam's (normalised) score.
        if not new_beams:
            break
        if len(finished) >= beam_width:
            best_live = max(s / max(len(t), 1) ** length_penalty for t, s in new_beams)
            worst_kept = sorted((s / max(len(t), 1) ** length_penalty for t, s in finished),
                                reverse=True)[beam_width - 1]
            if worst_kept >= best_live:
                break
        if step == budget - 1:
            finished.extend(new_beams)          # out of budget: keep unfinished beams
            break

        beams = new_beams
        last = torch.tensor([[t[-1]] for t, _ in beams], dtype=torch.long, device=device)
        if use_cache:
            parent_index = torch.tensor(parents, dtype=torch.long, device=device)
            cache = _select_cache(cache, parent_index)   # reorders/expands rows to the live beams
            logits, cache = model.score_cached(last, cache)
        else:
            full = torch.tensor([prompt_ids + t for t, _ in beams], dtype=torch.long, device=device)
            logits = model.score(full)
        step_log_probs = torch.log_softmax(logits.float(), dim=-1)

    ranked = sorted(((t, s / max(len(t), 1) ** length_penalty) for t, s in finished),
                    key=lambda item: -item[1])
    return ranked[:max(beam_width, 1)]


def entity_surfaces(triples: list[str]) -> list[str]:
    """Names from subjects/objects, as they usually appear in text."""
    names = []
    for triple in triples:
        parts = [p.strip() for p in triple.split("|")]
        for value in (parts[0], parts[-1]):
            text = value.replace("_", " ").strip().strip('"').strip()
            text = re.sub(r"\s*\(.*\)$", "", text)                  # drop "(disambiguation)"
            if text and text.lower() not in (n.lower() for n in names):
                names.append(text)
    return names


def coverage(text: str, names: list[str]) -> float:
    if not names:
        return 0.0
    lowered = text.lower()
    return sum(name.lower() in lowered for name in names) / len(names)


def rerank(texts_and_scores: list[tuple[str, float]], triples: list[str]) -> str:
    """Pick the candidate with the highest entity coverage, then model score."""
    names = entity_surfaces(triples)
    return max(texts_and_scores, key=lambda item: (round(coverage(item[0], names), 6), item[1]))[0]